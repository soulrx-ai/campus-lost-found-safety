export type TranslationKey = keyof typeof translations;
export type TranslationParams = Readonly<Record<string, string | number>>;

export function isTranslationKey(value: string): value is TranslationKey {
  return Object.prototype.hasOwnProperty.call(translations, value);
}

export function translate(language: Language, key: TranslationKey, params?: TranslationParams): string {
  const template: string = translations[key][language];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params?.[name] === undefined ? match : String(params[name])
  );
}

// Only use for existing application-authored labels/messages. Never user content.
export function translateUiText(language: Language, text: string): string {
  return isTranslationKey(text) ? translate(language, text) : text;
}
